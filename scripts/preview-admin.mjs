import { cp, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { spawn, spawnSync } from 'node:child_process';
const repo = process.cwd();
const info = JSON.parse(await readFile('artifacts/shared-host-release.json', 'utf8'));
const root = await mkdtemp(join(repo, 'artifacts/admin-ui-'));
await cp(info.release, root, { recursive: true, filter: path => !path.split(/[\\/]/).includes('data') && !path.endsWith('.hash') });
const tomorrow = new Date(Date.now() + 2 * 86400000);
const parts = new Intl.DateTimeFormat('en-u-ca-persian', { timeZone: 'Asia/Tehran', year: 'numeric', month: '2-digit', day: '2-digit' }).formatToParts(tomorrow);
const value = name => parts.find(part => part.type === name).value;
const day = `${value('year')}-${value('month')}-${value('day')}`;
const php = resolve('artifacts/php-runtime/php.exe');
const args = ['-d', `extension_dir=${resolve('artifacts/php-runtime/ext')}`, '-d', 'extension=pdo_sqlite'];
const seed = spawnSync(php, [...args, 'tests/seed-admin-calendar.php', join(root, 'tina-booking-runtime'), day], { stdio: 'inherit' });
if (seed.status !== 0) process.exit(seed.status ?? 1);
await writeFile('artifacts/admin-ui-preview.json', JSON.stringify({ root, day }));
const child = spawn(php, [...args, '-S', '127.0.0.1:18232', '-t', join(root, 'public_html')], { stdio: 'inherit' });
process.on('SIGINT', () => child.kill());
console.log('Isolated administrator UI: http://127.0.0.1:18232/tina-administrator/');
