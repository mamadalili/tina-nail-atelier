import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { todayInTehran } from '../src/lib/jalali';
import { receiptSchema } from '../src/features/booking/receipt-model';

const base = new URL(process.argv[2] ?? 'http://127.0.0.1:18227');
assert.equal(base.hostname, '127.0.0.1', 'Use only isolated local storage for automated HTTP writes');
const api = new URL('/tina-preview/api/booking.php', base);
const data = { name: 'آزمایش محلی، مراجعه ندارد', phone: '09000000000', service: 'manicure', manicureType: 'gel', date: todayInTehran(new Date(Date.now() + 7 * 86400000)), period: '14-16', note: '', consent: true };
const key = randomUUID();
const post = (body: unknown, id = key, origin = base.origin) => fetch(api, { method: 'POST', headers: { Origin: origin, 'Content-Type': 'application/json', 'Idempotency-Key': id }, body: JSON.stringify(body) });
const health = await fetch(`${api}?action=health`);
assert.equal(health.status, 200);
assert.deepEqual(await health.json(), { enabled: true, notifications: false });
assert.equal((await post(data, key, 'https://foreign.invalid')).status, 403);
assert.equal((await fetch(api, { method: 'POST', headers: { Origin: base.origin }, body: '{}' })).status, 415);
assert.equal((await post({ ...data, note: 'x'.repeat(9000) })).status, 413);
assert.equal((await post(data, 'bad')).status, 400);
assert.equal((await post({ ...data, consent: false })).status, 422);
const first = await post(data);
assert.equal(first.status, 201);
assert.match(first.headers.get('cache-control')!, /no-store/);
const receipt = receiptSchema.parse((await first.json()).receipt);
const replay = await post(data);
assert.equal(replay.status, 200);
assert.deepEqual((await replay.json()).receipt, receipt);
const conflict = await post({ ...data, service: 'pedicure', manicureType: '' }, randomUUID());
assert.equal(conflict.status, 409);
assert.equal((await conflict.json()).code, 'SLOT_TAKEN');
const availability = await fetch(`${api}?date=${data.date}`);
assert.deepEqual(await availability.json(), { date: data.date, taken: ['14-16'] });
console.log('PASS HTTP: health, same-origin, JSON/size/key/consent checks, final receipt schema, durable retry, shared slot conflict and private availability');
